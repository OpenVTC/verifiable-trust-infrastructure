#!/usr/bin/env python3
"""Whole-tree documentation invariants that drift silently (#2636 – #2639).

Each check reads the tree as it is and compares it with what a document says
about it. None needs a build: the manifests come from `cargo metadata
--no-deps --offline`, which reads `Cargo.toml` files only.

1. **Crate map** (#2637). The dependency layers in the root `CLAUDE.md`,
   between the `crate-map:begin` / `crate-map:end` markers, are generated
   from the manifests: a crate's layer is the length of its longest chain of
   internal normal or build dependencies (dev-dependencies are not edges —
   they may point upward). `--write` regenerates the block. Every workspace
   member must also have a row in the crate table that follows it, and no row
   may name a crate that is not a member.
2. **Published-crate count** (#2636). Every "**N of M crates publish**" in
   `CLAUDE.md`, `RELEASING.md` and the engineering notes must match the
   manifests, and RELEASING.md's list of internal crates must be exactly the
   members with `publish = false`.
3. **Docs index** (#2639). Every page under `docs/0[1-4,6,7]-*/` must be a
   link target in `docs/README.md`.
4. **Relative links** (#2638). Every relative Markdown link in a tracked
   `*.md` file (CHANGELOGs and vendored bundles excepted) must name a file
   that exists, and an anchor into a Markdown file must name one of its
   headings (GitHub's slug rules). Links inside fenced code are ignored.

Run with no arguments to check (exit 1 on any failure, each with the fix);
`--write` rewrites the crate-map block in place, then checks.
"""

import json
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- crate-map:begin (generated by scripts/check-docs.py --write; do not edit by hand) -->"
END = "<!-- crate-map:end -->"

errors: list[str] = []


def fail(msg: str) -> None:
    errors.append(msg)


# ── Manifests ────────────────────────────────────────────────────────────


def metadata() -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--no-deps", "--offline", "--format-version", "1"],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return json.loads(out)


def internal_graph(meta: dict) -> tuple[dict[str, set[str]], dict[str, bool]]:
    """Member name → internal normal/build deps; member name → publishes."""
    members = {p["name"] for p in meta["packages"]}
    deps: dict[str, set[str]] = {}
    publishes: dict[str, bool] = {}
    for p in meta["packages"]:
        deps[p["name"]] = {
            d["name"]
            for d in p["dependencies"]
            if d.get("path") and d["name"] in members and d["kind"] != "dev" and d["name"] != p["name"]
        }
        # `publish = false` is `[]`; absent (or a registry list) publishes.
        publishes[p["name"]] = p["publish"] != []
    return deps, publishes


def layers(deps: dict[str, set[str]]) -> dict[str, int]:
    depth: dict[str, int] = {}

    def walk(n: str, stack: tuple[str, ...]) -> int:
        if n in depth:
            return depth[n]
        if n in stack:
            raise SystemExit(f"dependency cycle: {' → '.join(stack + (n,))}")
        d = 0 if not deps[n] else 1 + max(walk(x, stack + (n,)) for x in deps[n])
        depth[n] = d
        return d

    for n in deps:
        walk(n, ())
    return depth


def render_map(deps: dict[str, set[str]]) -> str:
    depth = layers(deps)
    by_layer: dict[int, list[str]] = defaultdict(list)
    for n, d in depth.items():
        by_layer[d].append(n)
    width = max(len(n) for n in deps) + 2
    lines = ["```text"]
    for d in sorted(by_layer):
        label = "leaves: no internal dependencies" if d == 0 else f"longest internal chain {d}"
        lines.append(f"Layer {d} ({label}):")
        for n in sorted(by_layer[d]):
            if not deps[n]:
                lines.append(f"  {n}")
                continue
            head = f"  {n.ljust(width)}→ "
            cont = " " * len(head)
            line = head
            for i, x in enumerate(sorted(deps[n])):
                piece = x + ("," if i < len(deps[n]) - 1 else "")
                if len(line) + len(piece) + 1 > 80 and line.strip() not in ("", "→"):
                    lines.append(line.rstrip())
                    line = cont
                line += piece + " "
            lines.append(line.rstrip())
        lines.append("")
    if lines[-1] == "":
        lines.pop()
    lines.append("```")
    return "\n".join(lines)


def check_crate_map(deps: dict[str, set[str]], write: bool) -> None:
    path = ROOT / "CLAUDE.md"
    text = path.read_text()
    if BEGIN not in text or END not in text:
        fail(f"CLAUDE.md: the `{BEGIN}` / `{END}` markers around the crate map are missing")
        return
    start = text.index(BEGIN) + len(BEGIN)
    stop = text.index(END)
    want = "\n" + render_map(deps) + "\n"
    if text[start:stop] != want:
        if write:
            path.write_text(text[:start] + want + text[stop:])
            print("CLAUDE.md: crate map regenerated")
        else:
            fail(
                "CLAUDE.md: the crate map does not match the manifests. "
                "Run `python3 scripts/check-docs.py --write` and commit the result."
            )

    # The crate table: every member has a row; every row names a member.
    rows: set[str] = set()
    table = re.search(r"^\| Crate \| Role \|\n(?:\|.*\n)+", text[stop:], re.M)
    if not table:
        fail("CLAUDE.md: no `| Crate | Role |` table after the crate map")
        return
    for m in re.finditer(r"^\| `([^`]+)` \|", table.group(0), re.M):
        name = m.group(1)
        brace = re.fullmatch(r"(.*)\{([^}]+)\}(.*)", name)
        if brace:
            rows.update(brace.group(1) + x + brace.group(3) for x in brace.group(2).split(","))
        else:
            rows.add(name)
    members = set(deps)
    for n in sorted(members - rows):
        fail(f"CLAUDE.md: crate table has no row for workspace member `{n}` — add `| `{n}` | <role> |`")
    for n in sorted(rows - members):
        fail(f"CLAUDE.md: crate table names `{n}`, which is not a workspace member — drop or rename the row")


# ── Published-crate count ────────────────────────────────────────────────

COUNT_RE = re.compile(r"\*\*(\d+) of (\d+) (?:workspace )?crates(?: publish)?\.?\*\*")
COUNT_FILES = ["CLAUDE.md", "RELEASING.md", "docs/04-reference/workspace-engineering-notes.md"]


def check_counts(publishes: dict[str, bool]) -> None:
    total = len(publishes)
    published = sum(publishes.values())
    internal = sorted(n for n, p in publishes.items() if not p)
    for f in COUNT_FILES:
        text = (ROOT / f).read_text()
        found = COUNT_RE.findall(text)
        if not found:
            fail(f"{f}: no '**N of M crates publish**' statement found (expected **{published} of {total} crates publish**)")
        for n, m in found:
            if (int(n), int(m)) != (published, total):
                fail(f"{f}: says **{n} of {m}**, the manifests say **{published} of {total} crates publish**")
    # RELEASING.md lists the internal crates between markers.
    text = (ROOT / "RELEASING.md").read_text()
    m = re.search(r"<!-- internal-crates:begin -->(.*?)<!-- internal-crates:end -->", text, re.S)
    if not m:
        fail("RELEASING.md: the <!-- internal-crates:begin/end --> list is missing")
        return
    listed = set(re.findall(r"`([a-z0-9-]+)`", m.group(1)))
    for n in sorted(set(internal) - listed):
        fail(f"RELEASING.md: `{n}` sets publish = false but is missing from the internal-crates list")
    for n in sorted(listed - set(internal)):
        fail(f"RELEASING.md: `{n}` is listed as internal but publishes (or is not a member)")


# ── Docs index ───────────────────────────────────────────────────────────


def check_docs_index() -> None:
    index = (ROOT / "docs" / "README.md").read_text()
    targets = {unquote(t.split("#")[0]) for t in re.findall(r"\]\(([^)\s]+)\)", index)}
    targets = {str((ROOT / "docs" / t).resolve().relative_to(ROOT)) for t in targets if not t.startswith(("http", "#"))}
    for d in sorted((ROOT / "docs").glob("0[1234670]-*")):
        if d.name.startswith("05-"):
            continue
        for page in sorted(d.rglob("*.md")):
            rel = str(page.relative_to(ROOT))
            if rel not in targets:
                fail(f"docs/README.md: {rel} is not in the index — add a link to it")


# ── Relative links ───────────────────────────────────────────────────────


def tracked_markdown() -> list[str]:
    files = subprocess.run(
        ["git", "ls-files", "*.md"], cwd=ROOT, capture_output=True, text=True, check=True
    ).stdout.split()
    skip = ("CHANGELOG.md",)
    return [
        f
        for f in files
        if not f.endswith(skip) and "/node_modules/" not in f and "/trust-tasks/" not in f
    ]


def strip_code(text: str) -> str:
    """Blank out fenced code blocks and inline code, keeping line count."""
    out = []
    fence = None
    for line in text.split("\n"):
        m = re.match(r"^\s*(```+|~~~+)", line)
        if fence:
            if m and m.group(1)[0] == fence[0] and len(m.group(1)) >= len(fence):
                fence = None
            out.append("")
            continue
        if m:
            fence = m.group(1)
            out.append("")
            continue
        out.append(re.sub(r"(`+)(?:(?!\1).)+?\1", "", line))
    return "\n".join(out)


_slug_cache: dict[Path, set[str]] = {}


def slugs(path: Path) -> set[str]:
    if path in _slug_cache:
        return _slug_cache[path]
    seen: dict[str, int] = {}
    out: set[str] = set()
    fence = None
    for line in path.read_text(errors="replace").split("\n"):
        m = re.match(r"^\s*(```+|~~~+)", line)
        if fence:
            if m and m.group(1)[0] == fence[0]:
                fence = None
            continue
        if m:
            fence = m.group(1)
            continue
        h = re.match(r"^#{1,6}\s+(.*?)\s*#*\s*$", line)
        if not h:
            continue
        title = h.group(1)
        title = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", title)  # links → text
        title = re.sub(r"<[^>]+>", "", title)  # inline HTML
        s = title.strip().lower()
        s = re.sub(r"[^\w\- ]", "", s)  # GitHub keeps letters, digits, _, -, space
        s = s.replace(" ", "-")
        n = seen.get(s, 0)
        seen[s] = n + 1
        out.add(s if n == 0 else f"{s}-{n}")
    for a in re.findall(r'<a\s+(?:name|id)="([^"]+)"', path.read_text(errors="replace")):
        out.add(a)
    _slug_cache[path] = out
    return out


LINK_RE = re.compile(r"(?<!\!)\[[^\]]*\]\(\s*<?([^)\s>]+)>?(?:\s+\"[^\"]*\")?\s*\)")


def check_links() -> None:
    for f in tracked_markdown():
        src = ROOT / f
        text = strip_code(src.read_text(errors="replace"))
        for lineno, line in enumerate(text.split("\n"), 1):
            for m in LINK_RE.finditer(line):
                target = m.group(1)
                if re.match(r"^[a-z][a-z0-9+.-]*:", target, re.I) or target.startswith("//"):
                    continue  # absolute URL, mailto:, …
                path_part, _, anchor = target.partition("#")
                path_part = unquote(path_part)
                if path_part:
                    dest = (src.parent / path_part).resolve()
                    if not dest.exists():
                        fail(f"{f}:{lineno}: link to `{target}` — no such file")
                        continue
                else:
                    dest = src.resolve()
                if anchor and dest.suffix == ".md" and dest.is_file():
                    if unquote(anchor).lower() not in slugs(dest):
                        fail(f"{f}:{lineno}: link to `{target}` — {dest.relative_to(ROOT)} has no heading with that anchor")


def main() -> int:
    write = "--write" in sys.argv[1:]
    meta = metadata()
    deps, publishes = internal_graph(meta)
    check_crate_map(deps, write)
    check_counts(publishes)
    check_docs_index()
    check_links()
    for e in errors:
        print(f"::error::{e}")
    if errors:
        print(f"\n{len(errors)} documentation check(s) failed.")
        return 1
    print("documentation checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
