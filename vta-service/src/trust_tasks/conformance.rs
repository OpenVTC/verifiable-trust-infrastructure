/// The sweep's scope: dispatched ∩ published. Derived, never hand-listed.
fn resolved_uris() -> BTreeSet<&'static str> {
    dispatched_uris()
        .into_iter()
        .filter(|u| trust_tasks_rs::schema_index::schema_for(u).is_some())
        .collect()
}

type ParseFn = fn(Value) -> Result<(), String>;
type ValidateFn = fn(&Value) -> Result<(), String>;

fn parses<T: DeserializeOwned>(v: Value) -> Result<(), String> {
    serde_json::from_value::<T>(v)
        .map(|_| ())
        .map_err(|e| e.to_string())
}

/// Validate against the embedded `payload.schema.json`, which is what the
/// dispatch spine actually runs (`validate_payload` → `against_schema`).
///
/// This is **not** what [`parses`] checks, and the gap is where a whole class
/// of defect lived. serde reads `null` into an `Option<T>` field happily; JSON
/// Schema types the same member `"string"` and rejects null outright. So a body
/// that serialized every unset member as `null` round-tripped through the
/// generated type — green sweep — and was refused by the first maintainer it
/// reached. `keys/create/0.1` shipped exactly that way: the witness below
/// serializes a real `CreateKeyBody` with `mnemonic: None`, it parsed, and
/// every live key creation over DIDComm/TSP failed with `null is not of type
/// "string"`. Both checks now run on every witness.
fn validates<T: ValidatedPayload>(v: &Value) -> Result<(), String> {
    T::validate_value(v).map_err(|e| e.to_string())
}

/// A representative request/response pair for one published, dispatched URI.
///
/// The request should be the serialization of the type the producer actually
/// sends, so the assertion is about **our wire form** rather than a hand-typed
/// fixture. A transcription only proves someone can type valid JSON: it stops
/// tracking the producer the moment the producer changes, and stays green while
/// live traffic fails. `dids/update` is the worked example — its witness was
/// transcribed, and #895 shipped anyway.
///
/// ## Where a transcription remains, and why
///
/// **14** of these witnesses still build their request with `json!`, and the
/// count is not the useful framing — what remains is three distinct situations,
/// only one of which is unfinished work. (The previous note said 21; it was
/// arithmetic, not measurement. The number above is counted from the table.)
///
/// - **`auth/{whoami,sessions-list,step-up/approve-response}`,
///   `task-consent/decision`** (5) — the VTA is the *consumer*; no `vta-sdk`
///   producer sends these, so there is no emission of ours to assert. A fixture
///   is the honest witness, and **nothing is owed here**.
/// - **`vault/*` (7), `device/list`** (8) — the caller supplies the whole
///   payload as a `Value` and the SDK is a pass-through contributing at most one
///   member. There is no SDK type, and giving them one is an **API decision**,
///   not a test change.
/// - **`messaging/ping`** (1) — a producer exists, but its payload is a single
///   required `nonce`. A body struct would guard nothing today: this defect
///   class lives in *unset optional* members, and ping has none. Worth folding
///   the day it gains a second member, not before.
///
/// The families that did have unset optionals — `keys/*` (#888), `webvh` (#924),
/// `device/*` (#925), `consent/*` (#928) — are folded, and their witnesses are
/// built from the producer's own body rather than transcribed.
struct Witness {
    request: Value,
    parse_request: ParseFn,
    validate_request: ValidateFn,
    response: Value,
    parse_response: ParseFn,
}

enum Conformance {
    Checked(Witness),
    /// Known non-conformance, kept visible and counted instead of silently
    /// tolerated. Every entry is a follow-up issue; the reason must name the
    /// drift precisely enough that the fix needs no re-diagnosis.
    ///
    /// **There are currently none, and that is the goal state rather than
    /// evidence the variant is surplus.** It is constructed only while a defect
    /// is outstanding — the last entry was `persona/attribute/list`, whose
    /// schema contradiction is fixed in trust-tasks-rs 0.17.10 — and the point
    /// of keeping it is that recording drift stays as easy as papering over it.
    /// A table with nowhere to say "this one does not round-trip, here is why"
    /// invites a fixture edited until it passes, which reports a
    /// non-conformant route as conformant and is the exact failure this whole
    /// module exists to catch.
    #[expect(
        dead_code,
        reason = "no drift outstanding; kept so the next one can be recorded rather than hidden"
    )]
    KnownDrift(&'static str),
}

macro_rules! checked {
    ($p:ty, $r:ty, $req:expr, $resp:expr) => {
        Conformance::Checked(Witness {
            request: $req,
            parse_request: parses::<$p>,
            validate_request: validates::<$p>,
            response: $resp,
            parse_response: parses::<$r>,
        })
    };
}

