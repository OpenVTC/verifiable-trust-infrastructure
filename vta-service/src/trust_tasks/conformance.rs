/// The request payload this table witnesses for `uri`, if it holds one.
///
/// Exposed for the audit-coverage census, which needs a schema-valid payload
/// per dispatched task and should not carry a second copy of these fixtures —
/// two sets would drift, and the one that drifted would be the one nobody was
/// looking at.
///
/// `None` for a URI with no witness at all, and for a `KnownDrift` entry: that
/// variant records a shape the table already knows is wrong, and feeding it to
/// another sweep would spread one defect across two failures.
pub(super) fn request_payload_for(uri: &str) -> Option<Value> {
    table()
        .into_iter()
        .find(|(u, _)| *u == uri)
        .and_then(|(_, c)| match c {
            Conformance::Checked(w) => Some(w.request),
            Conformance::KnownDrift(_) => None,
        })
}

// ─── The sweep ───────────────────────────────────────────────────────────

/// Coverage: the witness table and the derived census agree exactly, in both
/// directions. A sibling stream rebinding a URI onto a published spec lands
/// here first — that is the point.
#[test]
fn every_published_dispatched_uri_has_a_witness() {
    let expected = resolved_uris();
    let mut covered = BTreeSet::new();
    for (uri, _) in table() {
        assert!(
            covered.insert(uri),
            "duplicate witness entry for {uri} — one entry per URI"
        );
    }

    let missing: Vec<_> = expected.difference(&covered).collect();
    assert!(
        missing.is_empty(),
        "these dispatched URIs are published in the registry but have no \
         conformance witness:\n  {}\n\nAdd a `checked!` entry (request + \
         response built from the slice's wire types), or — only for a real, \
         understood non-conformance — a `KnownDrift` entry with a reason. If \
         this fired after a rebase, a sibling consolidation stream rebound a \
         task onto a published URI; the sweep is asking for its witness.",
        missing
            .iter()
            .map(|s| s.to_string())
            .collect::<Vec<_>>()
            .join("\n  ")
    );

    let stale: Vec<_> = covered.difference(&expected).collect();
    assert!(
        stale.is_empty(),
        "these witnesses cover URIs that are no longer both dispatched and \
         published:\n  {}\n\nRemove them (or fix the constant they name).",
        stale
            .iter()
            .map(|s| s.to_string())
            .collect::<Vec<_>>()
            .join("\n  ")
    );
}

/// Correctness: every witness's request parses as the generated `Payload`
/// and its response as the generated `Response` — and the check has teeth:
/// a drifted (unknown-member) form of each MUST be rejected, so a witness
/// cannot pass vacuously against a schema that accepts anything.
#[test]
fn every_witnessed_task_round_trips_through_its_generated_types() {
    let mut drift: Vec<String> = Vec::new();

    for (uri, conformance) in table() {
        let w = match conformance {
            Conformance::Checked(w) => w,
            Conformance::KnownDrift(reason) => {
                assert!(
                    !reason.trim().is_empty(),
                    "{uri}: KnownDrift entries must state the drift"
                );
                drift.push(format!("{uri}: {reason}"));
                continue;
            }
        };

        (w.parse_request)(w.request.clone())
            .unwrap_or_else(|e| panic!("{uri}: request is not canonical: {e}\n{:#}", w.request));
        (w.parse_response)(w.response.clone())
            .unwrap_or_else(|e| panic!("{uri}: response is not canonical: {e}\n{:#}", w.response));

        // And the request against the schema itself — the check the dispatch
        // spine runs on arrival. Parsing is strictly weaker: serde reads
        // `null` into an `Option<T>` where the schema types the member
        // `"string"` and refuses it. See [`validates`].
        //
        // Request-only: `trust-tasks-rs` codegen emits `ValidatedPayload` for
        // `Payload` but not for `Response` (0.4 and 0.5 alike), so there is no
        // embedded response schema to check against. The response side keeps
        // its parse check; closing that half needs the codegen to emit the
        // response schema, which is an upstream change.
        (w.validate_request)(&w.request).unwrap_or_else(|e| {
            panic!(
                "{uri}: request fails its own payload schema: {e}\n{:#}",
                w.request
            )
        });

        // Teeth: an unknown member must be rejected on both sides. The
        // generated types carry `deny_unknown_fields` wherever the spec closes
        // the object — `additionalProperties: false`, or `unevaluatedProperties`
        // on a composed one, which trust-tasks-rs 0.17.2 also honours. A URI for
        // which this stops holding needs a KnownDrift-style review, not a silent
        // pass: the check below injects an unknown member, so a type that
        // accepts it makes the whole witness pass vacuously.
        for (side, value, parse) in [
            ("request", &w.request, w.parse_request),
            ("response", &w.response, w.parse_response),
        ] {
            let mut drifted = value.clone();
            drifted
                .as_object_mut()
                .unwrap_or_else(|| panic!("{uri}: {side} witness must be a JSON object"))
                .insert("__conformance_sweep_drift".into(), json!(true));
            assert!(
                parse(drifted).is_err(),
                "{uri}: the generated {side} type accepted an unknown member — \
                 this witness can pass vacuously and proves nothing"
            );
        }
    }

    // Debt is visible in the test output every run, not buried in a table.
    for line in &drift {
        eprintln!("KNOWN DRIFT (follow-up issue required): {line}");
    }
}
