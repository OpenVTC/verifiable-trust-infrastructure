//! The schema-conformance sweep (#857): every task this dispatcher binds to a
//! **published** canonical URI must carry that URI's wire shape.
//!
//! ## Why this exists
//!
//! Two parity checks already run — every SDK constant is dispatched
//! (routing), and every dispatched `spec/` URI exists in the registry
//! (coverage, `vtc-service/tests/trust_task_manifest.rs`). Nothing checked
//! **correctness**: that a task bound to a published URI actually speaks that
//! URI's schema. Folding a task onto a *published* URI silently turns
//! `validate_payload` on at the dispatch spine, and a non-canonical body then
//! fails on live traffic with no compile-time signal — which is exactly how
//! `acl/update` shipped broken (#856, via #842).
//!
//! ## How it works
//!
//! The URI census is **derived, not hand-maintained**: `dispatched_uris()`
//! (generated by `dispatch_table!` from the same declarations as the match
//! arms) filtered to what `trust_tasks_rs::schema_index::schema_for`
//! resolves. Every URI in that set MUST have an entry in [`table`] — a
//! [`Witness`] carrying a representative request and response, or an
//! annotated [`Conformance::KnownDrift`] debt entry. The witness's request
//! must parse as the generated `specs::…::Payload` and the response as
//! `specs::…::Response`; the generated types carry `deny_unknown_fields`
//! plus the spec's required set.
//!
//! The request is then validated against its embedded
//! `payload.schema.json` — the same check `validate_payload` runs on the
//! dispatch spine. Parsing alone is strictly weaker and let a whole class of
//! defect through: serde accepts `null` into an `Option<T>` field, JSON
//! Schema types that member `"string"` and rejects it. `keys/create/0.1`
//! shipped a body that serialized every unset member as `null`, its witness
//! parsed green, and live key creation over DIDComm/TSP failed on arrival.
//! See [`validates`].
//!
//! **Non-vacuity is enforced mechanically.** The `acl/update` defect
//! survived three PRs because an assertion of the form "adding a forbidden
//! member makes this fail" passed while the body was *already* failing for
//! an unrelated reason. Here every witness is drifted (an unknown member is
//! injected) after the good case passes, and the drifted form MUST be
//! rejected — a schema that accepts anything cannot produce a green row.
//!
//! ## Typed bodies, or raw JSON
//!
//! Witnesses are written **typed when the spec preceded the type, raw JSON
//! when it did not — and the second case is a debt**, not a style choice.
//!
//! A typed witness is the stronger form: it proves *our types* conform,
//! rather than that someone can hand-write a body the schema accepts. But it
//! only proves that when the type did not derive its shape from the same
//! misreading that produced the body. If it did, the witness asserts the code
//! agrees with itself and passes green over the defect.
//!
//! That is not hypothetical. When the `vta/contexts/*` and `vta/webvh/*`
//! schemas arrived (#1015), two of the producer types were already wrong —
//! `create_did_webvh` sent `context_id` where the schema names `contextId`,
//! and `update_context` dropped `contextPolicy` on the floor. Witnesses built
//! from those types would have encoded both defects and reported conformance.
//! So the 22 went in as raw JSON, against the schema as the authority.
//!
//! It is the same principle `scripts/check-bindings-conformance.mjs` applies
//! one layer down in `dtgwg-trust-tasks-tf`, where the binding rules are
//! deliberately re-implemented rather than imported from the generator: a
//! check that shares a source with the thing it checks has stopped being a
//! check. Its header makes the trade explicit — a re-implementation can be
//! wrong, but a wrong one disagrees loudly, where a shared one agrees
//! silently.
//!
//! Which makes the retro-fit a real step rather than tidying. Converting those
//! 22 to typed bodies turns "the schema accepts a shape someone wrote" into
//! "our types conform" — and it is sound only now that #1015 has corrected the
//! types. Done earlier it would have laundered the bugs into a green row.
//!
//! ## When this fails after a rebase
//!
//! Sibling consolidation streams are rebinding URIs. A newly bound published
//! URI fails the coverage assertion here **by design** — add a witness (or,
//! with a stated reason, a debt entry) for it. That is this check doing its
//! job, not an obstacle to route around.
//!
//! It has already happened once, and the shape is worth keeping: #864 folded
//! the `did-templates` family onto new URIs, the census dropped the old ones,
//! and the *stale-witness* direction of the coverage assertion fired. Both
//! directions matter — a witness for a URI nothing dispatches any more is as
//! much drift as a dispatched URI with no witness, and only the first tells
//! you a fold landed.
//!
//! And then the other direction fired for the same family: the
//! `trust-tasks-rs` 0.2.43 → 0.2.51 bump indexed the six 2.0 specs, the
//! derived census picked them straight back up, and the missing-witness
//! assertion asked for all six. Neither half was hand-listed — a fold
//! upstream and a dependency bump each moved the census on their own.

